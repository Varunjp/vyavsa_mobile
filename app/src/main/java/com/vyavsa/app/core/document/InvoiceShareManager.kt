package com.vyavsa.app.core.document

import android.content.Context
import android.content.Intent
import androidx.core.content.FileProvider
import com.vyavsa.app.core.printer.InvoicePrintData
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.ResponseBody
import java.io.File
import java.io.FileOutputStream

/**
 * Handles generating and dispatching invoice PDFs through Android's native
 * ACTION_SEND share flow with secure FileProvider content URIs.
 *
 * Implements a shared authoritative backend PDF pipeline (downloading byte-for-byte
 * the exact PDF generated by the backend and used by the web application), with
 * automatic resilient fallback to the local native PDF generator when offline.
 */
object InvoiceShareManager {

    /**
     * Authoritative share workflow:
     * 1. If [pdfDownloader] is provided, attempts to stream the backend-generated PDF.
     * 2. If download succeeds, saves to cache and shares via FileProvider.
     * 3. If download is unavailable or fails (e.g. offline), renders locally using [InvoicePdfGenerator].
     */
    suspend fun shareSalePdf(
        context: Context,
        invoiceNumber: String,
        fallbackPrintData: InvoicePrintData? = null,
        pdfDownloader: (suspend () -> ResponseBody)? = null
    ): Result<Unit> = withContext(Dispatchers.IO) {
        val invoicesDir = File(context.cacheDir, "invoices").apply {
            if (!exists()) mkdirs()
        }
        val safeInvoiceNumber = invoiceNumber
            .replace(Regex("[^a-zA-Z0-9_-]"), "_")
            .take(32)
            .ifBlank { "INV_${System.currentTimeMillis()}" }
        val targetFile = File(invoicesDir, "invoice-$safeInvoiceNumber.pdf")

        var downloadSuccess = false
        if (pdfDownloader != null) {
            try {
                val responseBody = pdfDownloader()
                responseBody.byteStream().use { input ->
                    FileOutputStream(targetFile).use { output ->
                        input.copyTo(output)
                    }
                }
                if (targetFile.exists() && targetFile.length() > 0L) {
                    downloadSuccess = true
                }
            } catch (_: Exception) {
                downloadSuccess = false
            }
        }

        if (!downloadSuccess) {
            if (fallbackPrintData != null) {
                val genResult = InvoicePdfGenerator.generateInvoicePdf(context, fallbackPrintData)
                if (genResult.isFailure) {
                    return@withContext Result.failure(
                        genResult.exceptionOrNull() ?: Exception("Failed to generate PDF document")
                    )
                }
            } else if (!targetFile.exists() || targetFile.length() == 0L) {
                return@withContext Result.failure(Exception("Invoice PDF could not be retrieved"))
            }
        }

        dispatchShareIntent(context, targetFile, invoiceNumber)
    }

    suspend fun shareInvoicePdf(
        context: Context,
        printData: InvoicePrintData
    ): Result<Unit> {
        return shareSalePdf(
            context = context,
            invoiceNumber = printData.invoiceNumber,
            fallbackPrintData = printData,
            pdfDownloader = null
        )
    }

    private fun dispatchShareIntent(
        context: Context,
        pdfFile: File,
        invoiceNumber: String
    ): Result<Unit> {
        return try {
            val authority = "${context.packageName}.fileprovider"
            val contentUri = FileProvider.getUriForFile(context, authority, pdfFile)

            val shareIntent = Intent(Intent.ACTION_SEND).apply {
                type = "application/pdf"
                putExtra(Intent.EXTRA_STREAM, contentUri)
                putExtra(Intent.EXTRA_SUBJECT, "Invoice #$invoiceNumber")
                putExtra(Intent.EXTRA_TEXT, "Invoice #$invoiceNumber from Vyavsa Bill Book")
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
            }

            val chooser = Intent.createChooser(shareIntent, "Share Invoice PDF via").apply {
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            context.startActivity(chooser)
            Result.success(Unit)
        } catch (e: Exception) {
            Result.failure(e)
        }
    }
}
